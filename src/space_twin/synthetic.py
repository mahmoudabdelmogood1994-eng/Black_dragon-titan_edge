"""Synthetic Sentinel-2-like scene written as real GeoTIFFs.

*** SYNTHETIC. NOT SATELLITE DATA. *** It exists only so the pipeline can be
demonstrated offline. It writes the same file layout a real Sentinel-2 L2A
download has, so replacing it with real bands needs no code change.
Spectral values are plausible orders of magnitude, not calibrated.
"""
from __future__ import annotations
import json, os
import numpy as np
import rasterio
from rasterio.transform import from_origin
from scipy.ndimage import gaussian_filter
from config import Config
from geo import to_enu

H = W = 500
PX_DEG = 0.0004                  # ~44 m
LAT_TOP, LON_LEFT = 27.35, 33.70
# (lat, lon, radius_km, strength)  strength 1.0 -> NDCI ~ +0.2
PATCHES = [(27.278, 33.862, 1.6, 1.00),    # dense bloom, upstream of the intake
           (27.310, 33.800, 1.0, 0.85),    # smaller, moderate
           (27.200, 33.880, 1.2, 0.30)]    # weak, below default threshold


def make_scene(out_dir: str, cfg: Config, seed: int = 3) -> str:
    os.makedirs(out_dir, exist_ok=True)
    rng = np.random.default_rng(seed)
    tr = from_origin(LON_LEFT, LAT_TOP, PX_DEG, PX_DEG)
    rows, cols = np.mgrid[0:H, 0:W]
    lon = LON_LEFT + (cols + 0.5) * PX_DEG
    lat = LAT_TOP - (rows + 0.5) * PX_DEG
    coast = 100 + 12 * np.sin(rows / 35.0) + 6 * np.sin(rows / 9.0)
    land = cols < coast
    shore = (~land) & (cols < coast + 6)
    p = np.zeros((H, W))
    tex = 1 + 0.25 * gaussian_filter(rng.normal(size=(H, W)), 6) * 30
    for la, lo, r_km, s in PATCHES:
        e, n = to_enu(lat, lon, la, lo)
        p += s * np.exp(-((np.hypot(e, n) / 1000.0) / r_km) ** 2)
    p = np.clip(p * np.clip(tex, 0.6, 1.4), 0, 1.4)
    b = {"green": np.full((H, W), 0.032), "red": np.full((H, W), 0.012),
         "rededge": np.full((H, W), 0.010), "nir": np.full((H, W), 0.004)}
    b["red"] += 0.010 * p; b["rededge"] += 0.024 * p
    b["green"] += 0.006 * p; b["nir"] += 0.004 * p
    for k, v in (("green", .02), ("red", .02), ("rededge", .02), ("nir", .010)):
        b[k] = np.where(shore, b[k] + v, b[k])                  # turbid shallows
    for k, v in (("green", .22), ("red", .27), ("rededge", .29), ("nir", .33)):
        b[k] = np.where(land, v, b[k])                          # sand / scrub
    for _ in range(25):                                         # sun-glint speckle
        r_, c_ = rng.integers(60, H - 60), rng.integers(200, W - 20)
        b["red"][r_, c_], b["rededge"][r_, c_] = 0.010, 0.030
    names = {"green": "B03", "red": "B04", "rededge": "B05", "nir": "B08"}
    for k, arr in b.items():
        arr = np.clip(arr + rng.normal(0, 0.0015, (H, W)), 0.0005, 1).astype("float32")
        with rasterio.open(os.path.join(out_dir, f"SYNTHETIC_{names[k]}.tif"), "w",
                           driver="GTiff", height=H, width=W, count=1, dtype="float32",
                           crs="EPSG:4326", transform=tr) as dst:
            dst.write(arr, 1)
    with open(os.path.join(out_dir, "README_SYNTHETIC.txt"), "w") as f:
        f.write("SYNTHETIC scene generated by synthetic.py. Not satellite data.\n")
    with open(os.path.join(out_dir, "scenario.json"), "w") as f:
        json.dump(cfg.to_dict(), f, indent=2)
    return out_dir
